namespace GodotWithFSharp.CodeGenerator

open System
open System.IO
open System.Text
open System.Text.Json
open System.Security.Cryptography
open System.Collections.Generic

type OutputOptions =
  { Owner: string
    Inputs: string array
    AllowEmpty: bool
    AllowInputChange: bool
    AdoptExisting: bool }

type OutputChanges =
  { Write: string array
    Delete: string array
    Unchanged: string array }

[<CLIMutable>]
type OwnedOutputFile = { Name: string; Hash: string }

[<CLIMutable>]
type OutputManifest =
  { Version: int
    Owner: string
    Inputs: string array
    Files: OwnedOutputFile array }

[<CLIMutable>]
type OutputSnapshot =
  { Name: string
    Before: string
    Existed: bool
    AfterHash: string }

[<CLIMutable>]
type OutputJournal =
  { Version: int
    Files: OutputSnapshot array }

/// Each output directory has one owner. Godot owns .uid files; this writer preserves them.
module Output =
  let marker = "// <auto-generated by GodotWithFSharp.CodeGenerator>"
  let manifestName = ".godotwithfsharp.manifest.json"
  let private journalName = ".godotwithfsharp.transaction.json"

  let defaults =
    { Owner = "GodotWithFSharp"
      Inputs = [||]
      AllowEmpty = false
      AllowInputChange = false
      AdoptExisting = false }

  let private jsonOptions = JsonSerializerOptions(WriteIndented = true)

  let private serialize value =
    JsonSerializer.Serialize(value, jsonOptions).Replace("\r\n", "\n")
    + "\n"

  let private hash (content: string) =
    Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes content))

  let private read path =
    if File.Exists path then
      Some(File.ReadAllText path)
    else
      None

  let private currentHash path =
    read path
    |> Option.map hash
    |> Option.defaultValue ""

  let private owned (content: string) =
    use reader = new StringReader(content)
    reader.ReadLine() = marker

  let private validName (name: string) =
    not (String.IsNullOrWhiteSpace name)
    && Path.GetFileName name = name
    && not (
      name.Contains('/')
      || name.Contains('\\')
    )
    && name.EndsWith(".cs", StringComparison.Ordinal)
    && name.IndexOfAny(Path.GetInvalidFileNameChars()) < 0

  let private atomicWrite (path: string) (content: string) =
    let temporary =
      Path.Combine(
        Path.GetDirectoryName path,
        ".gfs-"
        + Guid.NewGuid().ToString("N")
        + ".tmp"
      )

    try
      File.WriteAllText(temporary, content, UTF8Encoding(false))
      File.Move(temporary, path, true)
    finally
      if File.Exists temporary then
        File.Delete temporary

  let private validate (options: OutputOptions) (files: GeneratedFile array) =
    if String.IsNullOrWhiteSpace options.Owner then
      invalidArg "options" "An output owner is required."

    if
      files.Length = 0
      && not options.AllowEmpty
    then
      invalidOp "Empty generation is refused. Use --allow-empty to remove this owner's generated files deliberately."

    let names = HashSet<string>(StringComparer.OrdinalIgnoreCase)

    for file in files do
      if
        not (validName file.Name)
        || not (names.Add file.Name)
      then
        invalidArg "files" $"Invalid or duplicate filename: {file.Name}."

      if
        isNull file.Content
        || not (owned file.Content)
      then
        invalidArg "files" $"Missing generated marker: {file.Name}."

  let private loadManifest (options: OutputOptions) directory =
    let path = Path.Combine(directory, manifestName)

    match read path with
    | Some content ->
      let manifest = JsonSerializer.Deserialize<OutputManifest>(content)

      if
        isNull (box manifest)
        || manifest.Version <> 1
        || isNull manifest.Files
        || isNull manifest.Inputs
      then
        invalidOp $"Invalid output manifest: {path}."

      if manifest.Owner <> options.Owner then
        invalidOp $"Output belongs to '{manifest.Owner}', not '{options.Owner}'."

      let names = HashSet<string>(StringComparer.OrdinalIgnoreCase)

      for file in manifest.Files do
        if
          not (validName file.Name)
          || not (names.Add file.Name)
          || String.IsNullOrEmpty file.Hash
        then
          invalidOp $"Invalid manifest entry: {file.Name}."

      if
        manifest.Inputs <> options.Inputs
        && not options.AllowInputChange
      then
        invalidOp "Input assembly set changed. Use --allow-input-change after reviewing the output plan."

      manifest
    | None ->
      let legacy =
        if Directory.Exists directory then
          Directory.GetFiles(directory, "*.cs")
          |> Array.filter (fun path -> owned (File.ReadAllText path))
        else
          [||]

      if
        legacy.Length > 0
        && not options.AdoptExisting
      then
        invalidOp "Legacy generated files require --adopt-existing before manifest ownership can be established."

      { Version = 1
        Owner = options.Owner
        Inputs = options.Inputs
        Files =
          legacy
          |> Array.map (fun path ->
            { Name = Path.GetFileName path
              Hash = currentHash path }
          ) }

  // Cheap preflight avoids creating an output directory or lock for ownership/path errors.
  // Content hashes are checked only under the lock; no preflight snapshot is reused there.
  let private checkOwnership directory (files: GeneratedFile array) (previous: OutputManifest) =
    let previousFiles =
      Dictionary<string, OwnedOutputFile>(StringComparer.OrdinalIgnoreCase)

    for file in previous.Files do
      previousFiles.Add(file.Name, file)

    for file in files do
      let path = Path.Combine(directory, file.Name)

      if Directory.Exists path then
        invalidOp $"Output path is a directory: {path}."

      match previousFiles.TryGetValue file.Name with
      | true, previous when previous.Name <> file.Name ->
        invalidOp $"Case-only output rename requires an explicit resource migration: {previous.Name} -> {file.Name}."
      | false, _ when File.Exists path -> invalidOp $"Refusing to overwrite a file not owned by this generator: {path}."
      | _ -> ()


  let private prepare (options: OutputOptions) directory (files: GeneratedFile array) =
    validate options files
    let previous = loadManifest options directory
    checkOwnership directory files previous

    // One content read per path for this locked plan (also used by read-only planning).
    let contents = Dictionary<string, string option>(StringComparer.OrdinalIgnoreCase)

    let existing name =
      match contents.TryGetValue name with
      | true, content -> content
      | _ ->
        let content = read (Path.Combine(directory, name))
        contents.Add(name, content)
        content

    for file in previous.Files do
      match existing file.Name with
      | Some content when hash content <> file.Hash ->
        invalidOp $"Generated file was edited: {Path.Combine(directory, file.Name)}. Restore it before generating."
      | _ -> ()

    let names = files |> Array.map _.Name |> Set.ofArray

    let writes, unchanged =
      files
      |> Array.partition (fun file -> existing file.Name <> Some file.Content)

    let deletes =
      previous.Files
      |> Array.filter (fun file ->
        not (names.Contains file.Name)
        && File.Exists(Path.Combine(directory, file.Name))
      )
      |> Array.map _.Name

    let manifest =
      { Version = 1
        Owner = options.Owner
        Inputs = options.Inputs
        Files =
          files
          |> Array.sortBy _.Name
          |> Array.map (fun file ->
            { Name = file.Name
              Hash = hash file.Content }
          ) }

    let content = serialize manifest

    { Write = writes |> Array.map _.Name
      Delete = deletes
      Unchanged = unchanged |> Array.map _.Name },
    writes,
    content

  /// Read-only plan, including all ownership and hash checks.
  let plan (options: OutputOptions) directory files =
    if File.Exists(Path.Combine(directory, journalName)) then
      invalidOp "An interrupted output transaction needs recovery. Run generation without --dry-run."

    let changes, _, _ = prepare options directory files
    changes

  let private restore directory =
    let path = Path.Combine(directory, journalName)

    match read path with
    | None -> ()
    | Some content ->
      let journal = JsonSerializer.Deserialize<OutputJournal>(content)

      if
        isNull (box journal)
        || journal.Version <> 1
        || isNull journal.Files
      then
        invalidOp "Invalid recovery journal."
      // Validate every snapshot and current state before recovering anything.
      for file in journal.Files do
        if
          file.Name <> manifestName
          && not (validName file.Name)
        then
          invalidOp "Invalid recovery path."

        if
          file.Existed
          && file.Name <> manifestName
          && not (owned file.Before)
        then
          invalidOp "Recovery snapshot is not generated source."

        let actual = currentHash (Path.Combine(directory, file.Name))
        let before = if file.Existed then hash file.Before else ""

        if
          actual <> before
          && actual <> file.AfterHash
        then
          invalidOp $"File changed after the interrupted transaction: {file.Name}. Recovery journal retained."

      for file in journal.Files do
        let target = Path.Combine(directory, file.Name)

        if file.Existed then
          atomicWrite target file.Before
        elif File.Exists target then
          File.Delete target

      File.Delete path

  let write (options: OutputOptions) directory files =
    validate options files

    if not (File.Exists(Path.Combine(directory, journalName))) then
      loadManifest options directory
      |> checkOwnership directory files

    Directory.CreateDirectory(directory)
    |> ignore

    use outputLock =
      new FileStream(
        Path.Combine(directory, ".godotwithfsharp.lock"),
        FileMode.OpenOrCreate,
        FileAccess.Write,
        FileShare.None
      )

    restore directory
    let changes, writes, manifest = prepare options directory files
    let manifestPath = Path.Combine(directory, manifestName)
    let manifestChanged = read manifestPath <> Some manifest

    let changesToWrite =
      [| yield! writes
         if manifestChanged then
           yield
             { Name = manifestName
               Content = manifest } |]

    let snapshots =
      [| for file in changesToWrite do
           let before = read (Path.Combine(directory, file.Name))

           yield
             { Name = file.Name
               Before = Option.defaultValue "" before
               Existed = Option.isSome before
               AfterHash = hash file.Content }
         for name in changes.Delete do
           yield
             { Name = name
               Before = File.ReadAllText(Path.Combine(directory, name))
               Existed = true
               AfterHash = "" } |]

    if snapshots.Length > 0 then
      let journalPath = Path.Combine(directory, journalName)
      atomicWrite journalPath (serialize { Version = 1; Files = snapshots })

      try
        for file in writes do
          atomicWrite (Path.Combine(directory, file.Name)) file.Content

        for name in changes.Delete do
          File.Delete(Path.Combine(directory, name))

        if manifestChanged then
          atomicWrite manifestPath manifest

        File.Delete journalPath
      with _ ->
        restore directory
        reraise ()

    changes
